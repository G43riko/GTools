/**
 * Enum representing the days of the week.
 * 
 * This enum provides a set of constants for the seven days of the week,
 * using three-letter abbreviations as both the enum member names and their string values.
 */
export enum Days {
    /** Monday */
    MON = "MON",
    /** Tuesday */
    TUE = "TUE",
    /** Wednesday */
    WED = "WED",
    /** Thursday */
    THU = "THU",
    /** Friday */
    FRI = "FRI",
    /** Saturday */
    SAT = "SAT",
    /** Sunday */
    SUN = "SUN",
}
